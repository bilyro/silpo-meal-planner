/**
 * Renders `tool_call_log` as a JSON-RPC transcript plus a metrics summary — spec §8 Phase 7 item 4
 * ("submit … a JSON-RPC log excerpt") and the source for the metrics slide.
 *
 *   npx tsx scripts/export-tool-log.ts                      # last 200 calls → docs/tool-call-log.md
 *   npx tsx scripts/export-tool-log.ts --limit 60 --since 2026-09-07T09:00:00Z
 *   npx tsx scripts/export-tool-log.ts --out /tmp/log.md
 *
 * Honesty about what this is: the *request* frames below are exactly what went over the wire —
 * tool name and arguments are stored verbatim by SilpoMcpClient. The *responses* are not stored,
 * deliberately: they carry the customer's real name, family, addresses and order history, and a
 * submission artefact is the last place that belongs. So each response line reports the outcome we
 * do record (ok/error, duration) and nothing is invented to fill the gap.
 */

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { and, desc, eq, gte } from 'drizzle-orm';
import { db, pool } from '../src/db/client.js';
import { toolCallLog, users } from '../src/db/schema.js';
import { redact } from './redact.js';

interface Options {
  limit: number;
  since?: Date;
  telegramChatId?: string;
  out: string;
}

function parseArgs(argv: string[]): Options {
  const opts: Options = { limit: 200, out: 'docs/tool-call-log.md' };
  for (let i = 0; i < argv.length; i += 2) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (value === undefined) throw new Error(`Missing value for ${flag}`);
    if (flag === '--limit') opts.limit = Number(value);
    else if (flag === '--since') opts.since = new Date(value);
    else if (flag === '--user') opts.telegramChatId = value;
    else if (flag === '--out') opts.out = value;
    else throw new Error(`Unknown flag ${flag}`);
  }
  if (!Number.isFinite(opts.limit) || opts.limit <= 0) throw new Error('--limit must be a positive number');
  if (opts.since && Number.isNaN(opts.since.getTime())) throw new Error('--since must be an ISO timestamp');
  return opts;
}

/** JSON on one line, the way a JSON-RPC frame appears on the wire. */
function frame(value: unknown): string {
  return JSON.stringify(value);
}

function percentile(sorted: number[], p: number): number {
  if (sorted.length === 0) return 0;
  const index = Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length));
  return sorted[index] ?? 0;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));

  let userId: number | undefined;
  if (opts.telegramChatId) {
    const [user] = await db.select().from(users).where(eq(users.telegramChatId, opts.telegramChatId)).limit(1);
    if (!user) throw new Error(`No user with telegram_chat_id=${opts.telegramChatId}`);
    userId = user.id;
  }

  const filters = [
    ...(userId !== undefined ? [eq(toolCallLog.userId, userId)] : []),
    ...(opts.since ? [gte(toolCallLog.createdAt, opts.since)] : []),
  ];

  // Newest-first from the database (that is what the index supports), then reversed so the
  // transcript reads forwards in time the way a real session log does.
  const rows = (
    await db
      .select()
      .from(toolCallLog)
      .where(filters.length > 0 ? and(...filters) : undefined)
      .orderBy(desc(toolCallLog.createdAt))
      .limit(opts.limit)
  ).reverse();

  if (rows.length === 0) {
    console.error('No tool calls matched. Run a plan through the bot first, or widen --since/--limit.');
    process.exitCode = 1;
    return;
  }

  const byTool = new Map<string, { total: number; ok: number; ms: number[] }>();
  for (const row of rows) {
    const entry = byTool.get(row.tool) ?? { total: 0, ok: 0, ms: [] };
    entry.total += 1;
    if (row.ok) {
      entry.ok += 1;
      // Failures include the retry chain and suppressed calls (ms: 0); mixing them into the
      // latency numbers would make both meaningless.
      entry.ms.push(row.ms);
    }
    byTool.set(row.tool, entry);
  }

  const okRows = rows.filter((r) => r.ok);
  const allMs = okRows.map((r) => r.ms).sort((a, b) => a - b);
  const first = rows[0]?.createdAt;
  const last = rows[rows.length - 1]?.createdAt;

  const lines: string[] = [];
  lines.push('# Silpo MCP — JSON-RPC call log excerpt');
  lines.push('');
  lines.push(
    'Generated by `npx tsx scripts/export-tool-log.ts` from the `tool_call_log` table, which',
    '`src/mcp/SilpoMcpClient.ts` writes to on **every** call — both the deterministic calls our own',
    'code makes and the ones the model improvises. Nothing here is hand-written.',
  );
  lines.push('');
  lines.push(
    '> The `tools/call` request frames are exactly what was sent to `https://mcp.silpo.ua/mcp`:',
    '> tool name and arguments are stored verbatim. Responses are **not** stored — they contain the',
    "> account holder's real name, family, addresses and orders — so each response line reports only",
    '> the recorded outcome (status and duration). Nothing has been reconstructed or invented.',
    '>',
    '> Argument keys that identify the account holder (address, coordinates, phone, recipient name)',
    '> are replaced with `«redacted»`. Product names, quantities, branch and cart ids are untouched —',
    '> they are the part worth reading.',
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`- Calls in this excerpt: **${rows.length}**`);
  lines.push(`- Distinct tools exercised: **${byTool.size}**`);
  lines.push(`- Succeeded: **${okRows.length}** · failed or suppressed: **${rows.length - okRows.length}**`);
  if (first && last) lines.push(`- Window: ${first.toISOString()} → ${last.toISOString()}`);
  lines.push(`- Latency of successful calls: p50 **${percentile(allMs, 50)} ms**, p95 **${percentile(allMs, 95)} ms**`);
  lines.push('');
  lines.push('| Tool | Calls | OK | p50 ms |');
  lines.push('|---|---:|---:|---:|');
  for (const [tool, s] of [...byTool.entries()].sort((a, b) => b[1].total - a[1].total)) {
    const sortedMs = [...s.ms].sort((a, b) => a - b);
    lines.push(`| \`${tool}\` | ${s.total} | ${s.ok} | ${percentile(sortedMs, 50)} |`);
  }
  lines.push('');
  lines.push('## Transcript');
  lines.push('');
  lines.push('```jsonrpc');
  rows.forEach((row, i) => {
    const id = i + 1;
    lines.push(
      `// ${row.createdAt.toISOString()}`,
      frame({
        jsonrpc: '2.0',
        id,
        method: 'tools/call',
        params: { name: row.tool, arguments: redact(row.argsJson ?? {}) },
      }),
      row.ok
        ? `// → ok in ${row.ms} ms (response body not stored: contains personal data)`
        : `// → FAILED in ${row.ms} ms: ${row.error ?? 'unknown error'}`,
    );
  });
  lines.push('```');
  lines.push('');

  const outPath = path.resolve(opts.out);
  await writeFile(outPath, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${rows.length} calls (${byTool.size} distinct tools) to ${outPath}`);
}

main()
  .catch((err: unknown) => {
    console.error(err instanceof Error ? err.message : err);
    process.exitCode = 1;
  })
  .finally(() => pool.end());
